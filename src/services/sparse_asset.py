"""Strict, local-only sparse asset selection for the JY grammar renderer.

This module is deliberately a small gate in front of the legacy visual
binding code.  It never searches, downloads, calls an image provider, or
turns a generic keyword intersection into a visual event.  A-roll remains the
truthful fallback whenever a concrete object/process is not evidenced by the
current transcript and an already cached, authorized asset.
"""

